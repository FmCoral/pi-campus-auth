def render(lines):
    buf = bytearray(1024)
    def pixel(x, y):
        if 0 <= x < 128 and 0 <= y < 64:
            buf[(y // 8) * 128 + x] |= 1 << (y % 8)
    def char12(x, y, ch):
        g = CJK[ch]
        for col in range(12):
            lo, hi = g[col], g[col + 12]
            for row in range(8):
                if lo & (1 << row):
                    pixel(x + col, y + row)
            for row in range(4):
                if hi & (1 << row):
                    pixel(x + col, y + 8 + row)
    def char_a(x, y, ch):
        """画 ASCII 字符（14 高变宽），返回宽度"""
        g = AFONT.get(ch) or AFONT[' ']
        w = g[0]
        for col in range(w):
            lo, hi = g[1 + col], g[1 + w + col]
            for row in range(8):
                if lo & (1 << row):
                    pixel(x + col, y + row)
            for row in range(6):
                if hi & (1 << row):
                    pixel(x + col, y + 8 + row)
        return w
    for i, line in enumerate(lines):
        x = 0
        for ch in line:                    # 中英混排：汉字 12px，ASCII 14 高变宽
            if ch in CJK:
                if x + 12 > 128:
                    break
                char12(x, i * 16 + 2, ch)
                x += 12
            else:
                g = AFONT.get(ch) or AFONT[' ']
                w = g[0]
                if x + w > 128:
                    break
                x += char_a(x, i * 16 + 1, ch) + 1
    return buf


class OLED:
    def __init__(self):
        self.fd = os.open(I2C_BUS, os.O_RDWR)
        fcntl.ioctl(self.fd, 0x0703, I2C_ADDR)
        for c in [0xAE, 0xD5,0x80, 0xA8,0x3F, 0xD3,0x00, 0x40,
                  0x8D,0x14, 0x20,0x00, 0xA1, 0xC8, 0xDA,0x12,
                  0x81,0xCF, 0xD9,0xF1, 0xDB,0x40, 0xA4, 0xA6,
                  0x21,0,127, 0x22,0,7, 0xAF]:
            os.write(self.fd, bytes([0x00, c]))

    def show(self, buf):
        os.write(self.fd, bytes([0x40]) + bytes(buf))


def get_clients():
    try:
        r = subprocess.run(['iw', 'dev', 'phy0-ap0', 'station', 'dump'],
                           capture_output=True, timeout=5)
        return r.stdout.count(b'Station ')
    except Exception:
        return -1


def check_online():
    try:
        r = subprocess.run(['ping', '-c', '1', '-W', '1', PROBE_HOST],
                           capture_output=True, timeout=3)
        return r.returncode == 0
    except Exception:
        return False


def get_net_bytes():
    b = f'/sys/class/net/{WAN_IF}/statistics'
    return int(open(b + '/rx_bytes').read()), int(open(b + '/tx_bytes').read())


def get_temp():
    try:
        return int(open('/sys/class/thermal/thermal_zone0/temp').read()) / 1000
    except Exception:
        return 0.0


def get_mem_pct():
    total = avail = 0
    for line in open('/proc/meminfo'):
        if line.startswith('MemTotal:'):
            total = int(line.split()[1])
        elif line.startswith('MemAvailable:'):
            avail = int(line.split()[1])
    return (total - avail) * 100 // total if total else 0


def read_cpu():
    p = open('/proc/stat').readline().split()[1:]
    v = list(map(int, p))
    return v[3] + v[4], sum(v)


def load_total():
    try:
        p = open(STATE_FILE).read().split()
        return int(p[0]), int(p[1])
    except Exception:
        return 0, 0


def save_total(rx, tx):
    with open(STATE_FILE, 'w') as f:
        f.write(f'{rx} {tx}')


def fmt_speed(bps):
    kb = bps / 1024
    return f'{int(kb)}KB/s' if kb < 1024 else f'{kb / 1024:.1f}MB/s'


def fmt_gb(b):
    return f'{b / 1073741824:.1f}'


